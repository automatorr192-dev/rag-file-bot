import asyncio

import db
from rag import ingest

DEMO = {
    "Правила возврата.txt": (
        "Магазин «Северный Лис». Выдуманные правила для демонстрации. "
        "Возврат принимается в течение 14 дней с момента получения. "
        "Вскрытую упаковку аксессуаров принимаем при наличии полной комплектации. "
        "Расходники со вскрытой упаковкой не принимаются. "
        "Для заявки укажите номер заказа и причину возврата."
    ),
    "Доставка.txt": (
        "Курьерская доставка по городу занимает 1–2 рабочих дня. "
        "Выдача в пункте самовывоза доступна со следующего рабочего дня. "
        "После передачи курьеру трек-номер появится в личном кабинете."
    ),
    "Каталог и гарантия.txt": (
        "Настольная лампа LX-410 имеет гарантию 24 месяца. "
        "На кабель LX-411 действует гарантия 6 месяцев. "
        "При неисправности поддержка просит номер заказа и описание проблемы."
    ),
}


async def seed(engine):
    for name, body in DEMO.items():
        await ingest(engine, 0, name, body.encode())


async def main():
    engine = db.make_engine()
    try:
        await seed(engine)
    finally:
        await engine.dispose()


if __name__ == "__main__":
    asyncio.run(main())
